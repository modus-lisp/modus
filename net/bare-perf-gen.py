#!/usr/bin/env python3
"""Regenerate the native code in net/bare-perf.lisp from net/bare-perf-fiq.s.

   python3 net/bare-perf-gen.py      (needs llvm-mc, llvm-objcopy, llvm-nm; any -16 suffix is found)

Rewrites the two word vectors and the label-offset constants between the GENERATED markers."""
import os, re, shutil, struct, subprocess, tempfile
here = os.path.dirname(os.path.abspath(__file__))
def tool(n):
    for c in (n, n + "-16", n + "-17", n + "-18", n + "-15"):
        if shutil.which(c): return c
    raise SystemExit("no " + n)
def assemble(src):
    d = tempfile.mkdtemp(); o = os.path.join(d, "x.o"); b = os.path.join(d, "x.bin")
    subprocess.check_call([tool("llvm-mc"), "-triple=aarch64", "-filetype=obj", src, "-o", o])
    subprocess.check_call([tool("llvm-objcopy"), "-O", "binary", "--only-section=.text", o, b])
    data = open(b, "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    labels = {}
    for line in subprocess.check_output([tool("llvm-nm"), o]).decode().splitlines():
        f = line.split()
        if len(f) == 3 and f[1] in "tT": labels[f[2]] = int(f[0], 16)
    return words, labels
def vec(name, words):
    rows = ["    " + " ".join("#x%08X" % w for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    return "(defparameter %s\n  #(\n%s))\n" % (name, "\n".join(rows))
fw, fl = assemble(os.path.join(here, "bare-perf-fiq.s"))
consts = [("+perf-stub-lit+", fl["stub_lit"]), ("+perf-handler+", fl["handler"]),
          ("+perf-ctl-lit+", fl["ctl_lit"]), ("+perf-arm+", fl["arm"]), ("+perf-disarm+", fl["disarm"]),
          ("+perf-vbar+", fl["vbar"]), ("+perf-barrier+", fl["barrier"])]
gen = (";;; ---- GENERATED by net/bare-perf-gen.py from bare-perf-fiq.s: edit that ----\n"
       + vec("*perf-fiq-words*", fw) + "\n"
       + "\n".join("(defconstant %s %d)" % c for c in consts)
       + "\n(defconstant +perf-stub-bytes+ %d)    ; the vector stub, literal included\n" % fl["handler"]
       + ";;; ---- END GENERATED ----\n")
p = os.path.join(here, "bare-perf.lisp"); s = open(p).read()
a = s.index(";;; ---- GENERATED"); b = s.index(";;; ---- END GENERATED ----\n") + len(";;; ---- END GENERATED ----\n")
open(p, "w").write(s[:a] + gen + s[b:])
print("bare-perf.lisp: %d FIQ words" % len(fw))
